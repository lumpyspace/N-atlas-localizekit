import { useEffect, useState } from "react";
import { ConnectionPill } from "./components/Connection";
import Config from "./screens/Config";
import Export from "./screens/Export";
import Overview from "./screens/Overview";
import Playground from "./screens/Playground";
import Tests from "./screens/Tests";
import { StoreProvider, useStore } from "./store";
import { ErrorNote } from "./ui";

export type Route = "overview" | "playground" | "tests" | "config" | "export";

const NAV: { id: Route; label: string }[] = [
  { id: "overview", label: "Overview" },
  { id: "playground", label: "Playground" },
  { id: "tests", label: "Test suite" },
  { id: "config", label: "Business & policy" },
  { id: "export", label: "Export" },
];

const fromHash = (): Route => {
  const h = window.location.hash.replace("#/", "") as Route;
  return NAV.some((n) => n.id === h) ? h : "overview";
};

export default function App() {
  return (
    <StoreProvider>
      <Shell />
    </StoreProvider>
  );
}

function Shell() {
  const [route, setRoute] = useState<Route>(fromHash);
  const { loadError } = useStore();

  useEffect(() => {
    const on = () => setRoute(fromHash());
    window.addEventListener("hashchange", on);
    return () => window.removeEventListener("hashchange", on);
  }, []);

  const go = (r: Route) => {
    window.location.hash = `/${r}`;
    window.scrollTo(0, 0);
  };

  return (
    <div className="min-h-screen">
      <header className="sticky top-0 z-10 border-b border-slate-200 bg-white/90 backdrop-blur">
        <div className="mx-auto flex max-w-7xl flex-wrap items-center gap-x-6 gap-y-2 px-4 py-3 sm:px-6">
          <button onClick={() => go("overview")} className="flex items-center gap-2" aria-label="LocalizeKit home">
            <span className="grid h-7 w-7 place-items-center rounded-md bg-forge-600 text-xs font-bold text-white">LK</span>
            <span className="text-[15px] font-bold text-ink">
              N-ATLAS <span className="text-forge-700">LocalizeKit</span>
            </span>
          </button>
          <nav className="order-3 -mx-1 flex w-full gap-1 overflow-x-auto sm:order-none sm:w-auto" aria-label="Main">
            {NAV.map((n) => (
              <a
                key={n.id}
                href={`#/${n.id}`}
                aria-current={route === n.id ? "page" : undefined}
                className={`whitespace-nowrap rounded-md px-3 py-1.5 text-sm font-medium ${route === n.id ? "bg-slate-100 text-ink" : "text-slate-600 hover:text-ink"}`}
              >
                {n.label}
              </a>
            ))}
          </nav>
          <div className="ml-auto"><ConnectionPill /></div>
        </div>
      </header>
      <main className="mx-auto max-w-7xl px-4 py-6 sm:px-6">
        {loadError && <div className="mb-4"><ErrorNote>{loadError}</ErrorNote></div>}
        {route === "overview" && <Overview go={go} />}
        {route === "playground" && <Playground />}
        {route === "tests" && <Tests />}
        {route === "config" && <Config />}
        {route === "export" && <Export />}
      </main>
      <footer className="mx-auto max-w-7xl px-4 pb-8 pt-2 text-xs text-slate-500 sm:px-6">
        Replies are generated by N-ATLAS (NCAIR1/N-ATLaS). AsoStyle Boutique and its details are fictional sample data.
        Automated checks are heuristics; they flag likely problems and do not prove a reply is correct.
      </footer>
    </div>
  );
}
